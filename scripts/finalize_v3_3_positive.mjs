/** EventSure V3.3: permissionless, one-attempt finalization after challenge window. */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {createAccount,createClient} from 'genlayer-js';
import {studionet} from 'genlayer-js/chains';
import {TransactionStatus} from 'genlayer-js/types';
const root=fileURLToPath(new URL('../',import.meta.url));
const proof=JSON.parse(fs.readFileSync(root+'deployments/STUDIONET_V3_3_DEPLOYMENT.json','utf8'));
const positive=JSON.parse(fs.readFileSync(root+'deployments/STUDIONET_V3_3_POSITIVE_QUALIFICATION.json','utf8'));
const code=fs.readFileSync(root+'contracts/EventSureV3_3.py');
const hash=crypto.createHash('sha256').update(code).digest('hex');
if(hash!=='63871815cd3a537dae86defe0f434aa5a08a551dce97a91ef8a76e71c0100abd'||hash!==proof.source_sha256)throw Error('Contract source fingerprint mismatch');
if(proof.address!==positive.address||proof.chain_id!==61999)throw Error('Unexpected contract or chain');
if(process.env.EVENTSURE_FINALIZE_AUTH!=='AUTHORIZED_STUDIONET_ONCE')throw Error('Missing authorization guard');
const client=createClient({chain:studionet,endpoint:'https://studio.genlayer.com/api'});
const id='EVS-APOLLO-POS-V33-E453D2D5E670';
const address=proof.address;
let state=await client.readContract({address,functionName:'get_case',args:[id]});
if(state.state==='FINALIZED'&&state.decision==='VERIFIED'){console.log('V33_FINALIZATION_ALREADY_COMPLETED=YES');process.exit(0);}
if(state.state!=='PRELIMINARY'||state.decision!=='VERIFIED'||state.challenge_count!==0)throw Error('Positive case no longer safe to finalize; no transaction sent');
if(Date.now()<=Date.parse(state.challenge_deadline)+5000)throw Error('Challenge window still open; no transaction sent');
const out=path.join(root,'artifacts','v3_3_finalization');
fs.mkdirSync(out,{recursive:true});
const journalFile=path.join(out,'attempt.json');
if(fs.existsSync(journalFile))throw Error('Prior attempt exists; reconcile');
const account=createAccount();
const journal={network:'Studionet',chain_id:61999,contract:address,case_id:id,source_sha256:hash,signer:account.address,attempt:new Date().toISOString(),challenge_deadline:state.challenge_deadline,broadcast_uncertain:true};
const save=()=>fs.writeFileSync(journalFile,JSON.stringify(journal,null,2)+'\n',{mode:0o600});
save();
const writer=createClient({chain:studionet,endpoint:'https://studio.genlayer.com/api',account});
const tx=await writer.writeContract({address,functionName:'finalize_case',args:[id],account});
journal.tx=tx;save();console.log('EVENTSURE_V33_FINALIZE_TX='+tx);
const receipt=await writer.waitForTransactionReceipt({hash:tx,status:TransactionStatus.FINALIZED,retries:150});
journal.execution_result=receipt?.consensus_data?.leader_receipt?.[0]?.execution_result??'UNKNOWN';
journal.votes=receipt?.consensus_data?.votes??{};
if(journal.execution_result!=='SUCCESS')throw Error('Finalization executed unsuccessfully; journal preserved');
state=await writer.readContract({address,functionName:'get_case',args:[id]});
journal.state=state.state;journal.decision=state.decision;journal.finalized_at=state.finalized_at;
if(state.state!=='FINALIZED'||state.decision!=='VERIFIED')throw Error('Final case state mismatch');
journal.broadcast_uncertain=false;journal.finished=new Date().toISOString();save();
console.log('EVENTSURE_V33_FINALIZATION=PASS');
console.log(JSON.stringify(journal));
