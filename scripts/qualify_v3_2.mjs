/** Live V3.2 qualification: fresh frozen case, real deadline and signed GenLayer resolution. */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {createAccount,createClient} from 'genlayer-js';
import {studionet} from 'genlayer-js/chains';
import {TransactionStatus} from 'genlayer-js/types';

const ROOT=fileURLToPath(new URL('../',import.meta.url));
const OUT=path.join(ROOT,'artifacts','v3_2');
const deployment=JSON.parse(fs.readFileSync(path.join(OUT,'deployment-proof.json'),'utf8'));
const SOURCE_HASH='9cc30efa9d1107afc30eb1e94d3d6b8cd0671f57f810c17d3801d6dba688b02f';
if(deployment.chain_id!==61999||deployment.source_sha256!==SOURCE_HASH||deployment.status!=='FINALIZED')throw Error('Missing verified V3.2 deployment proof');
const key=process.env.EVENTSURE_PRIVATE_KEY;
if(!/^0x[0-9a-fA-F]{64}$/.test(key??''))throw Error('Secure signing key unavailable');
const account=createAccount(key);
if(account.address.toLowerCase()!==deployment.signer.toLowerCase())throw Error('Deployment signer changed');
const client=createClient({chain:studionet,endpoint:'https://studio.genlayer.com/api',account});
const now=Date.now();
const id='EVS-LIVE-V32-'+crypto.randomBytes(6).toString('hex').toUpperCase();
const deadline=new Date(now+20*60*1000).toISOString();
const title='Apollo 11 historical lunar landing';
const question='Did the crewed Apollo 11 Lunar Module land on the Moon on July 20, 1969?';
const rule='Require NASA and U.S. National Archives independently published documents to substantiate that the crewed Apollo 11 lunar landing occurred on July 20, 1969, before the frozen case deadline. Reject any claim lacking historical timing evidence.';
const urls=['https://www.nasa.gov/mission/apollo-11/','https://www.archives.gov/exhibits/featured-documents/apollo-11-flight-plan'];
const journalPath=path.join(OUT,'qualification-attempt.json');
if(fs.existsSync(journalPath))throw Error('Qualification attempt journal exists; reconcile it before restarting');
const journal={id,source_sha256:deployment.source_sha256,address:deployment.address,signer:account.address,deadline,question,rule,urls,transactions:{},started:new Date().toISOString(),status:'IN_PROGRESS'};
const save=()=>fs.writeFileSync(journalPath,JSON.stringify(journal,null,2)+'\n',{mode:0o600});
const ensure=(ok,msg)=>{if(!ok)throw Error(msg)};
async function write(stage,method,args){
 journal.transactions[stage]={attempted:new Date().toISOString(),broadcast_uncertain:true};save();
 const tx=await client.writeContract({address:deployment.address,functionName:method,args,account});
 journal.transactions[stage].hash=tx;save();
 console.log('V32_'+stage.toUpperCase()+'_TX='+tx);
 const receipt=await client.waitForTransactionReceipt({hash:tx,status:TransactionStatus.FINALIZED,retries:150});
 const result=receipt?.consensus_data?.leader_receipt?.[0]?.execution_result;
 journal.transactions[stage].execution_result=result??'UNKNOWN';
 journal.transactions[stage].broadcast_uncertain=false;save();
 ensure(result==='SUCCESS','GenLayer '+stage+' did not execute successfully: '+result);
 return receipt;
}
save();
console.log('EVENTSURE_V3_2_QUALIFICATION_STARTED='+id);
await write('create','create_case',[id,title,question,rule,deadline,JSON.stringify(urls),'[]',0n]);
await write('freeze','freeze_case',[id]);
const pause=Math.max(0,Date.parse(deadline)-Date.now()+10000);
if(pause>22*60*1000)throw Error('Unexpectedly long deadline wait');
console.log('EVENTSURE_V3_2_WAITING_FOR_DEADLINE_MS='+pause);
await new Promise(resolve=>setTimeout(resolve,pause));
await write('resolve','resolve_case',[id]);
const state=await client.readContract({address:deployment.address,functionName:'get_case',args:[id]});
ensure(state?.state==='PRELIMINARY','Qualification not in PRELIMINARY state');
ensure(['VERIFIED','INCONCLUSIVE'].includes(state?.decision),'Unexpected on-chain verdict');
journal.final_state=state.state;
journal.verdict=state.decision;
journal.assessment=state.assessment;
journal.status=state.decision==='VERIFIED'?'VERIFIED_PATH_PROVEN':'INCONCLUSIVE_PATH_PROVEN';
journal.completed=new Date().toISOString();
save();
console.log(JSON.stringify({qualification:journal.status,case:id,contract:deployment.address,source_sha256:SOURCE_HASH,verdict:state.decision,transactions:journal.transactions},null,2));
if(state.decision!=='VERIFIED')console.log('POSITIVE_VERIFIED_QUALIFICATION=NOT_PROVEN');
